#!/usr/bin/env bash
#
# Creates the release signing key for DuoLink, and the keystore.properties file the Gradle build
# reads. Run this ONCE, on your own machine, and then keep both outputs somewhere safe.
#
#   ./scripts/make-release-keystore.sh
#
# Why this is a script you run rather than something the build does automatically: the key signs every
# future release of the app. Android refuses to install an update signed by a different key, so losing
# it means every user must uninstall (and lose their local data) before they can move to a new build.
# And anyone who obtains it can publish an "update" under your identity. That is a decision a human
# makes deliberately, with a backup, not something a CI job does silently.
#
# The password is generated for you. Copy it into a password manager before you close the terminal:
# it is not stored anywhere in this repository or in this script.

set -euo pipefail

cd "$(dirname "$0")/.."

KEYSTORE_PATH="keystore/duolink-release.jks"
PROPS_PATH="keystore.properties"
ALIAS="duolink"
VALIDITY_DAYS=10000          # ~27 years. Play Store requires validity past 2033.
KEY_SIZE=4096

fail() { printf '\nERROR: %s\n' "$1" >&2; exit 1; }

command -v keytool >/dev/null 2>&1 || fail "keytool not found. Install a JDK (17 or newer) and re-run."
command -v openssl >/dev/null 2>&1 || fail "openssl not found. Install OpenSSL and re-run."

if [ -e "$KEYSTORE_PATH" ]; then
  fail "$KEYSTORE_PATH already exists.
Refusing to overwrite it: overwriting the signing key silently breaks updates for every existing
installation. If you really have lost the key and must start over, move the old file aside yourself
first, and expect that no existing install can be upgraded."
fi

if [ -e "$PROPS_PATH" ]; then
  fail "$PROPS_PATH already exists. Move it aside first if you intend to re-create it."
fi

mkdir -p "$(dirname "$KEYSTORE_PATH")"
chmod 700 "$(dirname "$KEYSTORE_PATH")"

# Generate a strong, URL-safe password (no shell-special characters, so it cannot be mangled by the
# properties file or by a CI secret store).
PASSWORD="$(openssl rand -base64 48 | tr -d '\n+/=' | cut -c1-40)"
[ "${#PASSWORD}" -ge 32 ] || fail "password generation produced something too short"

printf '\nGenerating a %s-bit RSA key in %s ...\n' "$KEY_SIZE" "$KEYSTORE_PATH"
printf 'You will be prompted for a password - USE THE ONE PRINTED BELOW, not your own.\n\n'

printf 'The generated password is:\n\n    %s\n\n' "$PASSWORD"
printf 'Copy it to a password manager NOW. It is not saved anywhere else.\n\n'
printf 'Press Enter when you have copied it, or Ctrl-C to abort. '
read -r _

# Non-interactive keytool: all inputs supplied explicitly, so nothing is mistyped.
keytool -genkeypair \
  -keystore "$KEYSTORE_PATH" \
  -alias "$ALIAS" \
  -keyalg RSA \
  -keysize "$KEY_SIZE" \
  -validity "$VALIDITY_DAYS" \
  -storepass "$PASSWORD" \
  -keypass "$PASSWORD" \
  -dname "CN=DuoLink, OU=Android, O=DuoLink, L=, ST=, C=" \
  >/dev/null 2>&1 || fail "keytool failed. Check that the path is writable and that no keystore exists yet."

chmod 600 "$KEYSTORE_PATH"

cat > "$PROPS_PATH" <<PROPS
# Generated by scripts/make-release-keystore.sh. DO NOT COMMIT - it is in .gitignore.
# Paths are relative to the DuoLink/ directory (rootProject).
storeFile=$KEYSTORE_PATH
storePassword=$PASSWORD
keyAlias=$ALIAS
keyPassword=$PASSWORD
PROPS
chmod 600 "$PROPS_PATH"

# Prove the key can actually sign before declaring success: a keystore that cannot be opened is worse
# than no keystore, because the build would fail later with a misleading error.
keytool -list -keystore "$KEYSTORE_PATH" -storepass "$PASSWORD" -alias "$ALIAS" >/dev/null 2>&1 \
  || fail "the keystore was created but cannot be opened - treat it as broken and start over"

SHA="$(sha256sum "$KEYSTORE_PATH" | cut -d' ' -f1)"
CERT="$(keytool -list -v -keystore "$KEYSTORE_PATH" -storepass "$PASSWORD" -alias "$ALIAS" 2>/dev/null \
  | grep -i 'SHA256:' | head -1 | sed 's/.*SHA256: //')"

cat <<DONE

Keystore created and verified.

  keystore      : $KEYSTORE_PATH
  properties    : $PROPS_PATH
  alias         : $ALIAS
  certificate   : SHA256 $CERT
  keystore hash : $SHA

BACK THESE UP, SEPARATELY FROM THIS MACHINE:

  1. $KEYSTORE_PATH
  2. $PROPS_PATH  (contains the password)
  3. The password in a password manager

If both copies live only on this machine, one disk failure ends your ability to
publish updates to this app.

Next step:

  cd DuoLink && ./gradlew assembleRelease

The build prints a warning when it cannot find keystore.properties. If you do not
see that warning, the release APK is signed with your own key. Verify with:

  \$ANDROID_HOME/build-tools/<version>/apksigner verify --print-certs \\
      app/build/outputs/apk/release/app-release.apk

DONE
